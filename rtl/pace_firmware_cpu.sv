// Pace 2500N experimental REAL-FIRMWARE executor, NOT a complete VR4110.
// Big-endian 32-bit MIPS + subset of MIPS16 actually observed in U202.
// 128 KiB real boot ROM in FPGA M10K; remaining flash and 16 MiB RAM on
// MiSTer DDR3. Every unimplemented instruction produces a visible HALT.
// Never claim to be running OpenTV unless the actual guest ROM reaches it.
module pace_firmware_cpu #(
    parameter EXPERIMENTAL_READY=0,
    parameter EXTERNAL_MMIO=0,
    parameter CHECKPOINT_PORT=0,
    parameter RETIRE_TIMING=0,
    // Instruction cache for KSEG0 fetches from DDR (FPGA performance only;
    // the NEC VR4110 also caches KSEG0). 16 KiB, direct mapped, 16-byte
    // lines with a valid bit per 8-byte DDR word, so CACHE index/hit
    // operations address the same lines as the real primary I-cache.
    parameter ICACHE=0
) (
    input  wire        clk,
    input  wire        reset,
    input  wire        full_flash_loaded,
    input  wire  [1:0] mmio_policy, // 0 halt, 1 zero, 2 all ones, 3 one
    input wire checkpoint_hold, checkpoint_wr,
    input wire [6:0] checkpoint_index,
    input wire [31:0] checkpoint_data,
    output wire io_req, io_we,
    output wire [31:0] io_addr, io_wdata,
    output wire [1:0] io_size,
    input wire [31:0] io_rdata,
    input wire io_ready, io_irq,
    // Request/ack CPU memory port, adapted in top to MiSTer DDRAM bus.
    output wire        mem_req,
    output wire        mem_we,
    output wire [28:0] mem_addr,
    output wire [63:0] mem_wdata,
    output wire  [7:0] mem_be,
    input  wire        mem_accept,
    input  wire        mem_rvalid,
    input  wire [63:0] mem_rdata,
    output reg  [31:0] pc = 32'hBFC00000,
    output reg  [31:0] instruction = 0,
    output reg  [31:0] retired = 0,
    output reg  [31:0] ram_writes = 0,
    output reg  [31:0] last_ram_address = 0,
    output reg  [31:0] last_mmio_address = 0,
    output reg  [31:0] last_mmio_value = 0,
    output reg  [31:0] last_mmio_read = 0,
    output reg  [31:0] mmio_writes = 0,
    output reg  [31:0] guessed_reads = 0,
    output reg   [7:0] halt_code = 0,
    output reg         mips16 = 0,
    output reg         reached_mips16 = 0,
    output reg  [31:0] interrupt_count = 0
);
    // Contract: bootloader_words.hex contains U202[000000:020000], in
    // big-endian 32-bit words. Regenerated by tools/verify_firmware.py.
    // ONE synchronous M10K ROM read port. The old implementation exposed
    // multiple separately addressed reads, including a continuous video
    // hex viewer. That arrangement risked pathological ROM mux synthesis.
    // Every firmware read is explicitly scheduled through S_ROMREAD.
    reg [14:0] rom_request_addr = 15'd0;
    reg [3:0]  rom_next_state = 4'd0;
    wire [31:0] rom_q;
    pace_bootrom boot_memory (
        .clk(clk), .address(rom_request_addr), .q(rom_q)
    );

    localparam [28:0] DDR_RAM = 29'h06000000; // 0x30000000 byte physical DDR
    localparam [28:0] DDR_ROM = 29'h06400000; // 0x32000000 byte physical DDR
    localparam [3:0] S_FETCH=0, S_ROMFETCH=1, S_EXEC=2,
                     S_ROMLOAD=3, S_BUSREQ=4, S_BUSWAIT=5,
                     S_BUSCOMPLETE=6, S_HALT=7, S_M16_JUMP=8,
                     S_ROMREAD=9, S_M16_EXTEND=10, S_MULDIV=11, S_MMIO=12, S_BOUNDARY=13,
                     S_ILOOKUP=14, S_ICHECK=15;
    localparam [1:0] K_FETCH=0, K_LOAD=1, K_STORE=2, K_HALF=3;
    reg [3:0] state = S_FETCH;
    reg [31:0] gpr[0:31];
    reg [31:0] cp0[0:31];
    reg [31:0] hi=0,lo=0;
    reg [31:0] branch_target=0;
    reg [31:0] branch_pc=0;
    reg branch_pending=0,branch_to16=0;
    reg delay_slot=0,branch_mode16=0,timer_armed=0;
    // CP0 Count runs at MasterOut. Firmware reloads Compare with 202500 and
    // the EMMA timer with 810000 for the same 10 ms tick, so Count is the
    // timer clock / 4: one Count increment per four retired instructions in
    // the instruction-domain timebase (see pace_guide_peripherals).
    reg [1:0] count_prescale=0;
    wire count_step=count_prescale==2'd3;
    wire [5:0] delay_opcode=instruction[31:26];
    wire timer_match=!RETIRE_TIMING && timer_armed && (cp0[9]+32'd1==cp0[11]);
    wire [31:0] cause_with_timer=(EXTERNAL_MMIO ? ((cp0[13]&32'hfffffbff)|(io_irq?32'h400:32'd0)) : cp0[13]) | (timer_match?32'h8000:32'd0);
    wire interrupt_pending=cp0[12][0] && !cp0[12][1] && !cp0[12][2] &&
                           ((cp0[12]&cause_with_timer&32'hff00)!=0);
    reg [31:0] bus_virtual=0, store_data=0;
    reg [1:0] bus_kind=K_FETCH;
    reg [1:0] load_size=2; // 0 byte,1 half,2 word
    reg load_signed=0;
    reg io_write=0;
    reg [1:0] merge_load=0,merge_store=0,merge_offset=0;
    reg [31:0] merge_old=0;
    reg [4:0] load_dest=0;
    reg [63:0] read_latch=0;
    reg [15:0] jump_first=0, extend_prefix=0, extend_suffix=0;
    reg m16_extended=0, second_from_bus=0;
    reg [3:0] second_next_state=0;
    reg [31:0] second_word=0;
    wire [31:0] second_data=second_from_bus ? second_word : rom_q;
    wire [15:0] second_half=pc[1] ? second_data[31:16] : second_data[15:0];
    reg mul_start=0;
    reg [1:0] mul_operation=0;
    reg [31:0] mul_a=0,mul_b=0;
    wire mul_busy,mul_done,mul_error;
    wire [31:0] mul_hi,mul_lo;
    pace_muldiv arithmetic(.clk(clk),.reset(reset),.start(mul_start),
      .operation(mul_operation),.a(mul_a),.b(mul_b),.busy(mul_busy),
      .done(mul_done),.error(mul_error),.hi(mul_hi),.lo(mul_lo));

    // ---- Instruction cache (ICACHE=1) -------------------------------------
    // Data: 2048 x 64-bit DDR words. Tags: 1024 x {tag[17:0],valid[1:0]}
    // indexed by the 16-byte line, tag = DDR word address bits [28:11].
    // Reads are registered (M10K); the address is the current mem_addr.
    (* ramstyle="M10K" *) reg [63:0] icache_data[0:2047];
    (* ramstyle="M10K" *) reg [19:0] icache_tag[0:1023];
    reg [63:0] icache_data_q=0;
    reg [19:0] icache_tag_q=0;
    reg icache_tag_we=0,icache_data_we=0;
    reg [9:0] icache_tag_windex=0;
    reg [19:0] icache_tag_wdata=0;
    reg [10:0] icache_data_windex=0;
    reg [63:0] icache_data_wdata=0;
    reg [10:0] icache_sweep=0;      // bit 10 set once all tags are invalid
    reg icache_fill=0;
    reg [31:0] icache_hits=0;
    wire icache_ready=ICACHE && icache_sweep[10];
    // Lines are invalidated after any reset or checkpoint download.
    wire icache_flush=reset || (CHECKPOINT_PORT && checkpoint_hold);
    always @(posedge clk)begin
        icache_data_q<=icache_data[mem_addr[10:0]];
        icache_tag_q<=icache_tag[mem_addr[10:1]];
        if(icache_data_we)icache_data[icache_data_windex]<=icache_data_wdata;
        if(!icache_sweep[10])icache_tag[icache_sweep[9:0]]<=20'd0;
        else if(icache_tag_we)icache_tag[icache_tag_windex]<=icache_tag_wdata;
        if(icache_flush)icache_sweep<=0;
        else if(!icache_sweep[10])icache_sweep<=icache_sweep+11'd1;
    end
    wire icache_hit=icache_tag_q[19:2]==mem_addr[28:11] && icache_tag_q[mem_addr[0]];

    wire [31:0] rom_offset_pc = pc & 32'h001fffff;
    wire pc_is_rom = ((pc & 32'hffe00000)==32'hbfc00000) ||
                     ((pc & 32'hffe00000)==32'h9fc00000);
    wire local_rom_pc = pc_is_rom && rom_offset_pc < 32'h00020000;
    wire bus_is_rom = ((bus_virtual & 32'hffe00000)==32'hbfc00000) ||
                      ((bus_virtual & 32'hffe00000)==32'h9fc00000) ||
                      (EXTERNAL_MMIO && ((bus_virtual&32'h1fc00000)==32'h1f800000));
    wire bus_is_ram = ((bus_virtual & 32'hff000000)==32'h80000000) ||
                      ((bus_virtual & 32'hff000000)==32'ha0000000);
    assign mem_req = (state==S_BUSREQ);
    assign mem_we  = (bus_kind==K_STORE);
    assign mem_addr = bus_is_rom ? (DDR_ROM + (EXTERNAL_MMIO && (bus_virtual&32'h1fc00000)==32'h1f800000 ? {7'd0,bus_virtual[21:3]} : {8'd0,bus_virtual[20:3]})) :
                                   (DDR_RAM + {5'd0,bus_virtual[23:3]});
    wire [31:0] bswap = {store_data[7:0], store_data[15:8],
                         store_data[23:16], store_data[31:24]};
    wire [15:0] hswap = {store_data[7:0],store_data[15:8]};
    wire [63:0] store_bytes = (load_size==2) ? {32'd0,bswap} :
                              (load_size==1) ? {48'd0,hswap} :
                                               {56'd0,store_data[7:0]};
    assign mem_wdata = merge_store==1 ? ({32'd0,bswap} << (({1'b0,bus_virtual[2:0]}+{2'd0,merge_offset})*8)) :
                      merge_store==2 ? (({32'd0,bswap} >> ((3-merge_offset)*8)) << (bus_virtual[2:0]*8)) :
                      store_bytes << (bus_virtual[2:0]*8);
    assign mem_be = bus_kind!=K_STORE ? 8'hff :
                   merge_store==1 ? ((8'h0f<<merge_offset)&8'h0f)<<bus_virtual[2:0] :
                   merge_store==2 ? ((8'h0f>>(3-merge_offset))<<bus_virtual[2:0]) :
                   ((load_size==2) ? 8'h0f : (load_size==1) ? 8'h03 : 8'h01) << bus_virtual[2:0];
    assign io_req=EXTERNAL_MMIO && state==S_MMIO;
    assign io_we=io_write;
    assign io_addr=bus_virtual;
    assign io_wdata=store_data;
    assign io_size=load_size;
    wire [31:0] loaded_word=extract_ddr(read_latch,bus_virtual[2:0],2,0);
    wire [31:0] merged_word=merge_load==1 ?
        ((loaded_word<<(merge_offset*8)) | (merge_old & (32'hffffffff >> ((4-merge_offset)*8)))) :
        ((loaded_word>>((3-merge_offset)*8)) | (merge_old & (32'hffffffff << ((merge_offset+1)*8))));

    function automatic [31:0] sext16(input [15:0] v);
        sext16 = {{16{v[15]}},v};
    endfunction
    function automatic [31:0] sext8(input [7:0] v);
        sext8 = {{24{v[7]}},v};
    endfunction
    function automatic [31:0] extract_ddr(input [63:0] raw,
              input [2:0] addr, input [1:0] sz, input sign_extend);
        reg [63:0] aligned;
        reg [31:0] word;
        reg [15:0] half;
        begin
            aligned=raw >> (addr*8);
            word={aligned[7:0],aligned[15:8],aligned[23:16],aligned[31:24]};
            half={aligned[7:0],aligned[15:8]};
            case(sz)
                2: extract_ddr=word;
                1: extract_ddr=sign_extend ? {{16{half[15]}},half}: {16'd0,half};
                default:extract_ddr=sign_extend ? {{24{aligned[7]}},aligned[7:0]} : {24'd0,aligned[7:0]};
            endcase
        end
    endfunction
    function automatic [31:0] extract_rom(input [31:0] raw,
              input [1:0] addr, input [1:0] sz, input sign_extend);
        reg [31:0] shifted;
        begin
            shifted = raw >> ((3-addr)*8);
            case(sz)
                2: extract_rom=raw;
                1: begin
                    shifted = raw >> ((2-{addr[1],1'b0})*8);
                    extract_rom= sign_extend ? {{16{shifted[15]}},shifted[15:0]} : {16'd0,shifted[15:0]};
                end
                default: extract_rom= sign_extend ? {{24{shifted[7]}},shifted[7:0]} : {24'd0,shifted[7:0]};
            endcase
        end
    endfunction
    function automatic [4:0] reg16(input [2:0] r);
        case(r)
         0:reg16=16; 1:reg16=17; 2:reg16=2; 3:reg16=3;
         4:reg16=4;  5:reg16=5;  6:reg16=6; 7:reg16=7;
        endcase
    endfunction
    function automatic [31:0] mmio_guess(input [1:0] policy);
        case(policy)
            1:mmio_guess=32'd0;
            2:mmio_guess=32'hffffffff;
            3:mmio_guess=32'd1;
            default:mmio_guess=0;
        endcase
    endfunction
    // Complete one guest instruction, honouring MIPS32 branch delay slots.
    task automatic retire(input [31:0] sequential_pc, input branch_now,
                           input [31:0] target, input target_mode16);
        begin
            pc <= branch_pending ? branch_target : sequential_pc;
            mips16 <= branch_pending ? branch_to16 : mips16;
            if(branch_pending && branch_to16) reached_mips16 <= 1;
            branch_pending <= branch_now;
            branch_target <= target;
            branch_pc <= pc;
            branch_mode16 <= mips16;
            delay_slot <= !delay_slot && (branch_now ||
                (!mips16 && sequential_pc==(pc+32'd4) &&
                 (delay_opcode==1 || delay_opcode==4 || delay_opcode==5 || delay_opcode==6 || delay_opcode==7 ||
                  delay_opcode==20 || delay_opcode==21 || delay_opcode==22 || delay_opcode==23)));
            branch_to16 <= target_mode16;
            m16_extended <= 0;
            retired <= retired+1'd1;
            if(RETIRE_TIMING)begin
                count_prescale<=count_prescale+2'd1;
                cp0[9]<=count_before_retire+{31'd0,count_step};
                if(timer_armed && count_step && (cp0[11]-count_before_retire)==32'd1)cp0[13][15]<=1;
            end
            state <= RETIRE_TIMING ? S_BOUNDARY : S_FETCH;
        end
    endtask
    task automatic halt(input [7:0] why);
        begin halt_code<=why;state<=S_HALT;end
    endtask
    // Schedule a single ROM read; S_ROMREAD provides the full clock needed
    // for the M10K's registered output before the consumer state runs.
    task automatic request_rom(input [14:0] address,
                               input [3:0] resume_state);
        begin
            rom_request_addr <= address;
            rom_next_state <= resume_state;
            state <= S_ROMREAD;
        end
    endtask
    task automatic request_second(input [3:0] resume_state);
        reg [31:0] address;
        begin
            address=pc+32'd2;
            second_next_state<=resume_state;
            if((((address&32'hffe00000)==32'hbfc00000) ||
                ((address&32'hffe00000)==32'h9fc00000)) &&
                (address&32'h001fffff)<32'h20000) begin
                second_from_bus<=0;
                request_rom(address[16:2],resume_state);
            end else if(((((address&32'hffe00000)==32'hbfc00000) ||
                          ((address&32'hffe00000)==32'h9fc00000)) && full_flash_loaded) ||
                        (address&32'hff000000)==32'h80000000 ||
                        (address&32'hff000000)==32'ha0000000) begin
                second_from_bus<=1;bus_virtual<={address[31:2],2'b00};
                bus_kind<=K_HALF;
                state<=(icache_ready && address[31:29]==3'b100) ? S_ILOOKUP : S_BUSREQ;
            end else halt(8'h34);
        end
    endtask
    task automatic start_arithmetic(input [1:0] operation,
                                   input [31:0] lhs,rhs);
        begin
            mul_operation<=operation;mul_a<=lhs;mul_b<=rhs;
            mul_start<=1;state<=S_MULDIV;
        end
    endtask
    // Prepare a read or write of actual guest memory. Memory operations
    // finish the instruction only AFTER the DDR response is returned.
    task automatic access(input [31:0] va, input [1:0] sz,
           input sign_extend, input [4:0] dest, input is_write,
           input [31:0] value);
        begin
            if((sz==2 && va[1:0]!=0) || (sz==1 && va[0])) halt(8'h06);
            else if((sz==2 && va[2:0]>4) || (sz==1 && va[2:0]>6)) halt(8'h06);
            else begin
                bus_virtual<=va;
                load_size<=sz;
                load_signed<=sign_extend;
                load_dest<=dest;
                merge_load<=0;merge_store<=0;
                store_data<=value;
                bus_kind<=is_write ? K_STORE : K_LOAD;
                if(((va & 32'hffe00000)==32'hbfc00000 ||
                    (va & 32'hffe00000)==32'h9fc00000) &&
                     (va & 32'h001fffff)<32'h00020000) begin
                    if(is_write) halt(8'h07);
                    else begin
                        request_rom(va[16:2], S_ROMLOAD);
                    end
                end else if(((va & 32'hffe00000)==32'hbfc00000 ||
                             (va & 32'hffe00000)==32'h9fc00000) && full_flash_loaded && !is_write)
                    state<=S_BUSREQ;
                else if((va & 32'hff000000)==32'h80000000 ||
                        (va & 32'hff000000)==32'ha0000000)
                    state<=S_BUSREQ;
                else if(EXTERNAL_MMIO && ((va&32'h1fc00000)==32'h1f800000) && !is_write)
                    state<=S_BUSREQ;
                else if(EXTERNAL_MMIO && ((va&32'hfff00000)==32'hb0000000 ||
                        (va&32'hfff00000)==32'hb2000000 || (va&32'hffff0000)==32'hb4080000 ||
                        (va==32'hb4180000 && is_write && sz==0)))begin
                    io_write<=is_write;state<=S_MMIO;
                end
                else if((va & 32'hfff00000)==32'hb0000000 ||
                        (va & 32'hfff00000)==32'hb2000000) begin
                    if(is_write) begin
                        last_mmio_address<=va;
                        last_mmio_value<=value;
                        mmio_writes<=mmio_writes+1'd1;
                        retire(mips16?seq16:seq32,0,0,0);
                    end else begin
                        last_mmio_read<=va;
                        if(mmio_policy==0) halt(8'h03);
                        else begin
                            // Ready-bit injection is isolated to the explicitly
                            // experimental build and zero-response policy.
                            if(dest!=0) gpr[dest] <= extract_rom(
                                (EXPERIMENTAL_READY && mmio_policy==1 && va==32'hb0009120) ?
                                32'h00000020 : mmio_guess(mmio_policy),va[1:0],sz,sign_extend);
                            guessed_reads<=guessed_reads+1'd1;
                            retire(mips16?seq16:seq32,0,0,0);
                        end
                    end
                end else if(((va & 32'hffe00000)==32'hbfc00000 ||
                             (va & 32'hffe00000)==32'h9fc00000) && !full_flash_loaded)
                    halt(8'h04);
                else halt(8'h05);
            end
        end
    endtask

    wire [31:0] ir = instruction;
    wire [15:0] m16 = m16_extended ? extend_suffix : (pc[1] ? ir[15:0] : ir[31:16]);
    wire [5:0] op=ir[31:26], fn=ir[5:0];
    wire [4:0] rs=ir[25:21],rt=ir[20:16],rd=ir[15:11];
    wire [31:0] a=gpr[rs],b=gpr[rt];
    wire [31:0] count_before_retire=(!mips16 && op==16 && rs==4 && rd==9) ? b : cp0[9];
    wire [31:0] imm_se=sext16(ir[15:0]);
    wire [31:0] ea=a+imm_se;
    wire [31:0] seq32=pc+32'd4;
    wire [31:0] seq16=pc+(m16_extended?32'd4:32'd2);
    // MIPS16e manual MD00076, table 3-14: use this instruction's PC,
    // or the jump's first halfword address when executing its delay slot.
    wire [31:0] m16_base_pc=branch_pending ? branch_pc : pc;
    wire [31:0] jump_target={seq32[31:28],ir[25:0],2'b00};
    wire [2:0] rx=m16[10:8],ry=m16[7:5],rz=m16[4:2];
    wire [4:0] rxg=reg16(rx),ryg=reg16(ry),rzg=reg16(rz);
    wire [31:0] rxv=gpr[rxg],ryv=gpr[ryg];
    wire [31:0] imm8se=sext8(m16[7:0]);

    wire [15:0] ext_imm={extend_prefix[4:0],extend_prefix[10:5],m16[4:0]};
    wire [31:0] ext_signed=sext16(ext_imm);
    wire [31:0] m16_simm=m16_extended ? ext_signed : imm8se;
    wire [31:0] m16_uimm=m16_extended ? {16'd0,ext_imm} : {24'd0,m16[7:0]};
    wire [31:0] sp_offset=m16_extended ? ext_signed : ({24'd0,m16[7:0]}<<2);
    wire [31:0] off_byte=m16_extended ? ext_signed : {27'd0,m16[4:0]};
    wire [31:0] off_half=m16_extended ? ext_signed : ({27'd0,m16[4:0]}<<1);
    wire [31:0] off_word=m16_extended ? ext_signed : ({27'd0,m16[4:0]}<<2);
    wire [4:0] shift_amount=m16_extended ? extend_prefix[10:6] : (rz==0?5'd8:{2'd0,rz});
    wire [14:0] rr_imm={extend_prefix[3:0],extend_prefix[10:4],m16[3:0]};
    wire [31:0] rr_signed=m16_extended ? {{17{rr_imm[14]}},rr_imm} : {{28{m16[3]}},m16[3:0]};
    wire [4:0] full_dest={m16[4:3],ry};
    wire [31:0] jr16_target=m16[5] ? gpr[31] : rxv;
    integer j;
    always @(posedge clk) begin
        if(reset) begin
            state<=S_FETCH;pc<=32'hbfc00000;
            rom_request_addr<=15'd0;rom_next_state<=S_ROMFETCH;
            instruction<=0;retired<=0;ram_writes<=0;
            last_ram_address<=0;last_mmio_address<=0;last_mmio_value<=0;
            last_mmio_read<=0;mmio_writes<=0;guessed_reads<=0;
            halt_code<=0; mips16<=0;reached_mips16<=0;
            branch_pending<=0;branch_target<=0;branch_pc<=0;branch_to16<=0;
            delay_slot<=0;branch_mode16<=0;timer_armed<=0;interrupt_count<=0;
            hi<=0;lo<=0;m16_extended<=0;mul_start<=0;second_from_bus<=0;
            merge_load<=0;merge_store<=0;io_write<=0;icache_fill<=0;icache_hits<=0;count_prescale<=0;
            for(j=0;j<32;j=j+1) begin gpr[j]<=0;cp0[j]<=0;end
        end else if(CHECKPOINT_PORT && checkpoint_hold)begin
            mul_start<=0;state<=S_FETCH;branch_pending<=0;delay_slot<=0;m16_extended<=0;icache_fill<=0;
            if(checkpoint_wr)begin
                if(checkpoint_index<32)gpr[checkpoint_index[4:0]]<=checkpoint_data;
                else if(checkpoint_index<64)cp0[checkpoint_index[4:0]]<=checkpoint_data;
                else case(checkpoint_index)
                    64:pc<=checkpoint_data;
                    65:begin mips16<=checkpoint_data[0];timer_armed<=checkpoint_data[1];end
                    66:hi<=checkpoint_data;
                    67:lo<=checkpoint_data;
                    68:retired<=checkpoint_data;
                endcase
            end
        end else begin
            gpr[0]<=0;mul_start<=0;icache_tag_we<=0;icache_data_we<=0;
            // Count runs on the core clock, independently of instruction
            // retirement and DDR stalls. Exact NEC master-clock ratio remains
            // unmeasured; 50 MHz is an explicit experimental approximation.
            if(!RETIRE_TIMING)cp0[9]<=cp0[9]+32'd1;
            if(EXTERNAL_MMIO)cp0[13][10]<=io_irq;
            if(timer_match)cp0[13][15]<=1;
            case(state)
                S_FETCH: begin
                    if(interrupt_pending)begin
                        cp0[14]<=delay_slot ? (branch_pc|{31'd0,branch_mode16}) :
                                                 (pc|{31'd0,mips16});
                        cp0[13]<=(cause_with_timer&32'h7fffff83) | (delay_slot?32'h80000000:32'd0);
                        cp0[12][1]<=1;
                        pc<=cp0[12][22] ? 32'hbfc00380 : 32'h80000180;
                        mips16<=0;branch_pending<=0;delay_slot<=0;m16_extended<=0;
                        interrupt_count<=interrupt_count+32'd1;
                    end else if(local_rom_pc) begin
                        request_rom(pc[16:2], S_ROMFETCH);
                    end else if((pc_is_rom && full_flash_loaded) ||
                                (pc&32'hff000000)==32'h80000000 ||
                                (pc&32'hff000000)==32'ha0000000) begin
                        bus_virtual<={pc[31:2],2'b00};
                        bus_kind<=K_FETCH;
                        state<=(icache_ready && pc[31:29]==3'b100) ? S_ILOOKUP : S_BUSREQ;
                    end else if(pc_is_rom) halt(8'h04);
                    else halt(8'h08);
                end
                S_ROMREAD:state<=rom_next_state;
                S_ROMFETCH: begin instruction<=rom_q;state<=S_EXEC;end
                S_EXEC: begin
                    if(!mips16) begin
                      case(op)
                      0:case(fn)
                          0:begin if(rd!=0)gpr[rd]<=b<<ir[10:6];retire(seq32,0,0,0);end
                          2:begin if(rd!=0)gpr[rd]<=b>>ir[10:6];retire(seq32,0,0,0);end
                          3:begin if(rd!=0)gpr[rd]<=$signed(b)>>>ir[10:6];retire(seq32,0,0,0);end
                          4:begin if(rd!=0)gpr[rd]<=b<<a[4:0];retire(seq32,0,0,0);end
                          6:begin if(rd!=0)gpr[rd]<=b>>a[4:0];retire(seq32,0,0,0);end
                          7:begin if(rd!=0)gpr[rd]<=$signed(b)>>>a[4:0];retire(seq32,0,0,0);end
                          8:retire(seq32,1,{a[31:1],1'b0},a[0]); // JR: ISA mode from LSB
                          9:begin if((rd!=0))gpr[rd]<=pc+8;retire(seq32,1,{a[31:1],1'b0},a[0]);end
                          16:begin if(rd!=0)gpr[rd]<=hi;retire(seq32,0,0,0);end
                          18:begin if(rd!=0)gpr[rd]<=lo;retire(seq32,0,0,0);end
                          17:begin hi<=a;retire(seq32,0,0,0);end
                          19:begin lo<=a;retire(seq32,0,0,0);end
                          24,25,26,27:start_arithmetic(fn[1:0],a,b);
                          32,33:begin if(rd!=0)gpr[rd]<=a+b;retire(seq32,0,0,0);end
                          34,35:begin if(rd!=0)gpr[rd]<=a-b;retire(seq32,0,0,0);end
                          36:begin if(rd!=0)gpr[rd]<=a&b;retire(seq32,0,0,0);end
                          37:begin if(rd!=0)gpr[rd]<=a|b;retire(seq32,0,0,0);end
                          38:begin if(rd!=0)gpr[rd]<=a^b;retire(seq32,0,0,0);end
                          39:begin if(rd!=0)gpr[rd]<=~(a|b);retire(seq32,0,0,0);end
                          42:begin if(rd!=0)gpr[rd]<=($signed(a)<$signed(b));retire(seq32,0,0,0);end
                          43:begin if(rd!=0)gpr[rd]<=(a<b);retire(seq32,0,0,0);end
                          default:halt(8'h10);
                        endcase
                      1: begin
                          if(rt==0 || rt==1 || rt==2 || rt==3 || rt==16 || rt==17 || rt==18 || rt==19) begin
                              if(rt[4])gpr[31]<=pc+8;
                              if(rt[1] && !(rt[0]?($signed(a)>=0):($signed(a)<0)))retire(seq32+4,0,0,0);
                              else
                              retire(seq32,(rt[0]?($signed(a)>=0):($signed(a)<0)),
                                     seq32+(imm_se<<2),mips16);
                          end else halt(8'h11);
                      end
                      2,3:begin if(op==3)gpr[31]<=pc+8;retire(seq32,1,jump_target,0);end
                      4,5:retire(seq32,(op==4)?(a==b):(a!=b),seq32+(imm_se<<2),0);
                      6,7:retire(seq32,(op==6)?($signed(a)<=0):($signed(a)>0),seq32+(imm_se<<2),0);
                      8,9:begin if(rt!=0)gpr[rt]<=a+imm_se;retire(seq32,0,0,0);end
                      10:begin if(rt!=0)gpr[rt]<=($signed(a)<$signed(imm_se));retire(seq32,0,0,0);end
                      11:begin if(rt!=0)gpr[rt]<=(a<imm_se);retire(seq32,0,0,0);end
                      12:begin if(rt!=0)gpr[rt]<=a & {16'd0,ir[15:0]};retire(seq32,0,0,0);end
                      13:begin if(rt!=0)gpr[rt]<=a | {16'd0,ir[15:0]};retire(seq32,0,0,0);end
                      14:begin if(rt!=0)gpr[rt]<=a ^ {16'd0,ir[15:0]};retire(seq32,0,0,0);end
                      15:begin if(rt!=0)gpr[rt]<={ir[15:0],16'd0};retire(seq32,0,0,0);end
                      16:begin // MFC0/MTC0 and architectural ERET state
                          if(rs==0)begin if(rt!=0)gpr[rt]<=cp0[rd];retire(seq32,0,0,0);end
                          else if(rs==4)begin
                              if(rd==11)begin
                                  cp0[11]<=b;cp0[13][15]<=0;timer_armed<=1;
                              end else if(rd==13)cp0[13]<=(cause_with_timer&32'hfffffcff)|(b&32'h300);
                              else cp0[rd]<=b;
                              retire(seq32,0,0,0);
                          end
                          else if(ir==32'h42000018)begin
                              pc<=(cp0[12][2] ? cp0[30] : cp0[14])&32'hfffffffe;
                              mips16<=cp0[12][2] ? cp0[30][0] : cp0[14][0];
                              if(cp0[12][2])cp0[12][2]<=0;else cp0[12][1]<=0;
                              branch_pending<=0;delay_slot<=0;retired<=retired+1'd1;state<=RETIRE_TIMING?S_BOUNDARY:S_FETCH;
                              if(RETIRE_TIMING)begin
                                  count_prescale<=count_prescale+2'd1;
                                  cp0[9]<=cp0[9]+{31'd0,count_step};
                                  if(timer_armed && count_step && (cp0[11]-cp0[9])==32'd1)cp0[13][15]<=1;
                              end
                          end else halt(8'h12);
                      end
                      29:begin // JALX, critical real 32-bit -> MIPS16 path
                          gpr[31]<=pc+8;
                          retire(seq32,1,jump_target,1);
                      end
                      32,36:access(ea,0,op==32,rt,0,0);
                      33,37:access(ea,1,op==33,rt,0,0);
                      35:access(ea,2,0,rt,0,0);
                      34,38:begin // BE LWL/LWR, aligned memory fetch and register merge
                          access(ea&32'hfffffffc,2,0,rt,0,0);
                          merge_load<=op==34?1:2;merge_offset<=ea[1:0];merge_old<=b;
                      end
                      40:access(ea,0,0,0,1,b);
                      41:access(ea,1,0,0,1,b);
                      43:access(ea,2,0,0,1,b);
                      42,46:begin // BE SWL/SWR byte-enable partial stores
                          access(ea&32'hfffffffc,2,0,0,1,b);
                          merge_store<=op==42?1:2;merge_offset<=ea[1:0];
                      end
                      47:begin
                          // CACHE: primary I-cache operations (cache field 00) other
                          // than Fill invalidate the 16-byte line at the effective
                          // address index. Hit ops invalidate without a tag compare
                          // (a safe superset). D-cache ops remain no-ops: there is
                          // no data cache, every data access goes to DDR.
                          if(ICACHE && rt[1:0]==2'b00 && rt[4:2]!=3'b101)begin
                              icache_tag_we<=1;icache_tag_windex<=ea[13:4];icache_tag_wdata<=20'd0;
                          end
                          retire(seq32,0,0,0);
                      end
                      20,21:begin // branch likely: annul delay slot when not taken
                          if((op==20 ? a==b : a!=b))retire(seq32,1,seq32+(imm_se<<2),0);
                          else retire(seq32+4,0,0,0);
                      end
                      default:halt(8'h20);
                      endcase
                    end else begin
                      // MIPS16 compressed instruction decoder, NOT microMIPS.
                      // op coding from NEC VR4111 chapter 4 / Ghidra MIPS16.
                      case(m16[15:11])
                        0:begin gpr[rxg]<=gpr[29]+sp_offset;retire(seq16,0,0,1);end
                        1:begin
                          gpr[rxg]<=m16_extended ? (pc&32'hfffffffc)+ext_signed :
                                                   (m16_base_pc&32'hfffffffc)+sp_offset;
                          retire(seq16,0,0,1);
                        end
                        2:retire(seq16+((m16_extended ? ext_signed : {{21{m16[10]}},m16[10:0]})<<1),0,0,1);
                        3:begin
                          if(m16_extended || branch_pending)halt(8'h34);
                          else begin jump_first<=m16;request_second(S_M16_JUMP);end
                        end
                        4:retire(rxv==0 ? seq16+(m16_simm<<1):seq16,0,0,1);
                        5:retire(rxv!=0 ? seq16+(m16_simm<<1):seq16,0,0,1);
                        6:begin
                          if(m16[1:0]==1 || (m16_extended && (extend_prefix[5:0]!=0 || m16[4:2]!=0)))halt(8'h33);
                          else begin
                            case(m16[1:0])
                              0:gpr[rxg]<=ryv<<shift_amount;
                              2:gpr[rxg]<=ryv>>shift_amount;
                              3:gpr[rxg]<=$signed(ryv)>>>shift_amount;
                            endcase
                            retire(seq16,0,0,1);
                          end
                        end
                        8:begin
                          if(m16[4])halt(8'h30);
                          else begin gpr[ryg]<=rxv+rr_signed;retire(seq16,0,0,1);end
                        end
                        9:begin gpr[rxg]<=rxv+m16_simm;retire(seq16,0,0,1);end
                        10:begin gpr[24]<=($signed(rxv)<$signed(m16_uimm));retire(seq16,0,0,1);end
                        11:begin gpr[24]<=(rxv<m16_uimm);retire(seq16,0,0,1);end
                        12:begin
                          case(rx)
                            0:retire(gpr[24]==0 ? seq16+(m16_simm<<1):seq16,0,0,1);
                            1:retire(gpr[24]!=0 ? seq16+(m16_simm<<1):seq16,0,0,1);
                            2:access(gpr[29]+sp_offset,2,0,0,1,gpr[31]);
                            3:begin gpr[29]<=gpr[29]+(m16_extended?ext_signed:(imm8se<<3));retire(seq16,0,0,1);end
                            5:begin
                              if(m16_extended)halt(8'h31);
                              else begin if(full_dest!=0)gpr[full_dest]<=gpr[reg16(m16[2:0])];retire(seq16,0,0,1);end
                            end
                            7:begin
                              if(m16_extended)halt(8'h31);
                              else begin gpr[ryg]<=gpr[m16[4:0]];retire(seq16,0,0,1);end
                            end
                            default:halt(8'h31);
                          endcase
                        end
                        13:begin gpr[rxg]<=m16_uimm;retire(seq16,0,0,1);end
                        14:begin gpr[24]<=rxv^m16_uimm;retire(seq16,0,0,1);end
                        16:access(rxv+off_byte,0,1,ryg,0,0);
                        17:access(rxv+off_half,1,1,ryg,0,0);
                        18:access(gpr[29]+sp_offset,2,0,rxg,0,0);
                        19:access(rxv+off_word,2,0,ryg,0,0);
                        20:access(rxv+off_byte,0,0,ryg,0,0);
                        21:access(rxv+off_half,1,0,ryg,0,0);
                        22:access(m16_extended ? ((pc+ext_signed)&32'hfffffffc) :
                                   ((m16_base_pc+sp_offset)&32'hfffffffc),2,0,rxg,0,0);
                        24:access(rxv+off_byte,0,0,0,1,ryv);
                        25:access(rxv+off_half,1,0,0,1,ryv);
                        26:access(gpr[29]+sp_offset,2,0,0,1,rxv);
                        27:access(rxv+off_word,2,0,0,1,ryv);
                        28:begin
                          if(m16_extended || (m16[1:0]!=1 && m16[1:0]!=3))halt(8'h32);
                          else begin gpr[rzg]<=m16[1] ? rxv-ryv : rxv+ryv;retire(seq16,0,0,1);end
                        end
                        29:begin
                          if(m16_extended)halt(8'h32);
                          else case(m16[4:0])
                            0:begin
                              if(m16[6])gpr[31]<=(pc+(m16[7]?32'd2:32'd4))|32'd1;
                              if(m16[7])begin
                                pc<=jr16_target&32'hfffffffe;mips16<=jr16_target[0];
                                retired<=retired+1'd1;state<=S_FETCH;
                              end else retire(seq16,1,jr16_target&32'hfffffffe,jr16_target[0]);
                            end
                            2:begin gpr[24]<=($signed(rxv)<$signed(ryv));retire(seq16,0,0,1);end
                            3:begin gpr[24]<=(rxv<ryv);retire(seq16,0,0,1);end
                            4:begin gpr[ryg]<=ryv<<rxv[4:0];retire(seq16,0,0,1);end
                            6:begin gpr[ryg]<=ryv>>rxv[4:0];retire(seq16,0,0,1);end
                            7:begin gpr[ryg]<=$signed(ryv)>>>rxv[4:0];retire(seq16,0,0,1);end
                            10:begin gpr[24]<=rxv^ryv;retire(seq16,0,0,1);end
                            11:begin gpr[rxg]<=-ryv;retire(seq16,0,0,1);end
                            12:begin gpr[rxg]<=rxv&ryv;retire(seq16,0,0,1);end
                            13:begin gpr[rxg]<=rxv|ryv;retire(seq16,0,0,1);end
                            14:begin gpr[rxg]<=rxv^ryv;retire(seq16,0,0,1);end
                            15:begin gpr[rxg]<=~ryv;retire(seq16,0,0,1);end
                            16,18:begin
                              if(ry!=0)halt(8'h32);
                              else begin gpr[rxg]<=m16[1] ? lo : hi;retire(seq16,0,0,1);end
                            end
                            17:begin
                              case(ry)
                                0:gpr[rxg]<={24'd0,rxv[7:0]};
                                1:gpr[rxg]<={16'd0,rxv[15:0]};
                                4:gpr[rxg]<={{24{rxv[7]}},rxv[7:0]};
                                5:gpr[rxg]<={{16{rxv[15]}},rxv[15:0]};
                                default:halt(8'h32);
                              endcase
                              if(ry==0 || ry==1 || ry==4 || ry==5)retire(seq16,0,0,1);
                            end
                            24,25,26,27:start_arithmetic(m16[1:0],rxv,ryv);
                            default:halt(8'h32);
                          endcase
                        end
                        30:begin
                          if(m16_extended || branch_pending)halt(8'h35);
                          else begin extend_prefix<=m16;request_second(S_M16_EXTEND);end
                        end
                        default:halt(8'h30);
                      endcase
                    end
                end
                S_ROMLOAD:begin
                    if(load_dest!=0)gpr[load_dest]<=extract_rom(rom_q,bus_virtual[1:0],load_size,load_signed);
                    retire(mips16?seq16:seq32,0,0,0);
                end
                S_BUSREQ:if(mem_accept)begin
                    if(bus_kind==K_STORE)begin
                        // Keep fetched code coherent with CPU stores (any alias).
                        if(ICACHE)begin icache_tag_we<=1;icache_tag_windex<=mem_addr[10:1];icache_tag_wdata<=20'd0;end
                        ram_writes<=ram_writes+1'd1;
                        last_ram_address<=bus_virtual;
                        retire(mips16?seq16:seq32,0,0,0);
                    end else state<=S_BUSWAIT;
                end
                S_BUSWAIT:if(mem_rvalid)begin read_latch<=mem_rdata;state<=S_BUSCOMPLETE;end
                S_BUSCOMPLETE:begin
                    if(icache_fill)begin
                        icache_fill<=0;
                        icache_data_we<=1;icache_data_windex<=mem_addr[10:0];icache_data_wdata<=read_latch;
                        icache_tag_we<=1;icache_tag_windex<=mem_addr[10:1];
                        icache_tag_wdata<={mem_addr[28:11],
                            (icache_tag_q[19:2]==mem_addr[28:11] ? icache_tag_q[1:0] : 2'b00) |
                            (mem_addr[0] ? 2'b10 : 2'b01)};
                    end
                    if(bus_kind==K_FETCH)begin
                        instruction<=extract_ddr(read_latch,bus_virtual[2:0],2,0);
                        state<=S_EXEC;
                    end else if(bus_kind==K_HALF)begin
                        second_word<=extract_ddr(read_latch,bus_virtual[2:0],2,0);
                        state<=second_next_state;
                    end else begin
                        if(load_dest!=0)gpr[load_dest]<=merge_load!=0 ? merged_word : extract_ddr(read_latch,bus_virtual[2:0],load_size,load_signed);
                        retire(mips16?seq16:seq32,0,0,0);
                    end
                end
                S_M16_JUMP:begin
                    // first halfword gives target[25:16] in unusual split order.
                    // second halfword is at PC+2, read through the ROM port.
                    gpr[31]<=(pc+32'd6)|32'd1;
                    retire(pc+32'd4,1,
                          {pc[31:28],jump_first[4:0],jump_first[9:5],
                           second_half,2'b00},
                          ~jump_first[10]);
                end
                S_M16_EXTEND:begin
                    extend_suffix<=second_half;m16_extended<=1;
                    instruction<={extend_prefix,second_half};state<=S_EXEC;
                end
                S_MULDIV:if(mul_done)begin
                    if(mul_error)halt(8'h36);
                    else begin hi<=mul_hi;lo<=mul_lo;retire(mips16?seq16:seq32,0,0,0);end
                end
                S_HALT:begin end
                S_BOUNDARY:state<=S_FETCH;
                S_ILOOKUP:state<=S_ICHECK; // registered tag/data read of mem_addr
                S_ICHECK:begin
                    if(icache_hit)begin
                        icache_hits<=icache_hits+32'd1;
                        if(bus_kind==K_FETCH)begin
                            instruction<=extract_ddr(icache_data_q,bus_virtual[2:0],2,0);
                            state<=S_EXEC;
                        end else begin
                            second_word<=extract_ddr(icache_data_q,bus_virtual[2:0],2,0);
                            state<=second_next_state;
                        end
                    end else begin icache_fill<=1;state<=S_BUSREQ;end
                end
                S_MMIO:if(io_ready)begin
                    if(io_write)begin
                        last_mmio_address<=bus_virtual;last_mmio_value<=store_data;mmio_writes<=mmio_writes+1'd1;
                    end else begin
                        last_mmio_read<=bus_virtual;
                        if(load_dest!=0)gpr[load_dest]<=load_signed ?
                            (load_size==0 ? sext8(io_rdata[7:0]) : load_size==1 ? sext16(io_rdata[15:0]) : io_rdata) : io_rdata;
                    end
                    retire(mips16?seq16:seq32,0,0,0);
                end
                default:halt(8'hff);
            endcase
        end
    end
endmodule
